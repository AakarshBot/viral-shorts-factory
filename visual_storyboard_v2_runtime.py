def _render_scene(scene: dict[str, Any], mode: str, font_path: str | None) -> Image.Image:
    renderer = _RENDERERS.get(mode, _render_fact)
    return renderer(scene, font_path).convert("RGB")


async def build_storyboard_visuals(
    bot,
    script_data: dict[str, Any],
    language_cfg: dict[str, Any],
    format_mode: str = "regular",
):
    """Build Option 2 visual packages without image scraping."""
    scenes = script_data.get("script") or []
    if not isinstance(scenes, list) or not scenes:
        raise RuntimeError("Option 2 visual engine received no script scenes.")

    scene_dicts = [dict(scene) if isinstance(scene, dict) else {"voiceover": str(scene)} for scene in scenes]
    llm_modes, planner = _llm_plan(script_data, scene_dicts)
    modes = _normalise_modes(llm_modes, scene_dicts)
    font_path = language_cfg.get("font") if isinstance(language_cfg, dict) else None

    os.makedirs(bot.ASSETS_DIR, exist_ok=True)
    packages: list[list[dict[str, Any]]] = []
    provenance = list(script_data.get("visual_provenance") or []) if isinstance(script_data.get("visual_provenance"), list) else []
    print(f"\n🧠 Option 2 storyboard planner: provider={planner}; scenes={len(scene_dicts)}", flush=True)

    for index, (scene, mode) in enumerate(zip(scene_dicts, modes), 1):
        path = os.path.join(bot.ASSETS_DIR, f"scene_{index}_img.jpg")
        image = _render_scene(scene, mode, font_path)
        image.save(path, "JPEG", quality=95, optimize=True)

        entity = _clean(scene.get("primary_entity"))
        scene["visual_pipeline"] = PIPELINE_ID
        scene["visual_storyboard_mode"] = mode
        scene["visual_verified"] = True
        scene["visual_qc_blocked"] = False
        scene["visual_qc_block_reason"] = ""
        scene["visual_rescue_reason"] = ""
        scene["visual_fallback_reason"] = ""
        scene["visual_query_used"] = ""
        scene["visual_provider_query_used"] = ""
        scene["visual_original_path"] = path
        scene["visual_source"] = "editorial_graphic"
        scene["visual_type"] = f"STORYBOARD_{mode}"
        scene["visual_genre"] = "EDITORIAL_GRAPHIC"
        scene["asset_provenance"] = {
            "pipeline": PIPELINE_ID,
            "asset_type": "original_editorial_graphic",
            "planner": planner,
            "external_photo_used": False,
            "factual_copy_source": "verified_scene_voiceover",
            "source_credit": ORIGINAL_SOURCE_CREDIT,
        }

        packages.append([{
            "image": path,
            "text": "" if str(format_mode) == "top5" else scene.get("voiceover", ""),
            "narration_text": scene.get("voiceover", ""),
            "ai_generated": False,
            "source_type": "editorial_graphic",
            "visual_type": f"STORYBOARD_{mode}",
            "visual_genre": "EDITORIAL_GRAPHIC",
            "visual_verified": True,
            "visual_qc_blocked": False,
            "visual_qc_block_reason": "",
            "visual_rejection_counts": {},
            "visual_rescue_reason": "",
            "visual_fallback_reason": "",
            "visual_query_used": "",
            "manual_visual_query": "",
            "manual_visual_query_score": 0,
            "source_credit": ORIGINAL_SOURCE_CREDIT,
            "source_image_url": "",
            "asset_provenance": dict(scene["asset_provenance"]),
            "visual_asset_bank": [],
            "visual_original_path": path,
            "visual_manual_pool_mode": False,
            "visual_manual_pool_size": 0,
            "visual_manual_pool_query_stats": [],
            "visual_manual_pool": [],
            "visual_pipeline": PIPELINE_ID,
            "visual_storyboard_mode": mode,
        }])

        provenance.append({
            "type": "original_editorial_graphic",
            "pipeline": PIPELINE_ID,
            "scene_index": index,
            "mode": mode,
            "planner": planner,
            "source": "verified_scene_voiceover",
            "credit": ORIGINAL_SOURCE_CREDIT,
            "external_photo_used": False,
        })
        print(f"   [Option 2] Scene {index} -> {mode} | entity='{entity}'", flush=True)

    script_data["script"] = scene_dicts
    script_data["visual_pipeline"] = PIPELINE_ID
    script_data["visual_storyboard_plan"] = [
        {"scene_index": index, "mode": mode, "planner": planner}
        for index, mode in enumerate(modes, 1)
    ]
    script_data["visual_provenance"] = provenance
    script_data["visual_manual_queries"] = []
    script_data["visual_manual_pool"] = []
    script_data["visual_manual_pool_size"] = 0
    script_data["visual_manual_pool_query_stats"] = []
    script_data["visual_manual_pool_rejection_counts"] = {}
    script_data["ai_image_ratio"] = 0.0
    return packages
