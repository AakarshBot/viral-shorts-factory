"""Option 2 visual engine: original editorial storyboard graphics.

This module deliberately does NOT retrieve news photographs. It converts the
verified script/evidence into a scene-by-scene visual language using an LLM
only for editorial layout selection and deterministic Pillow renderers for the
actual pixels. No new factual claims are generated by the visual engine.
"""
from __future__ import annotations

import json
import os
import re
from typing import Any

import requests
from PIL import Image, ImageDraw, ImageFont

PIPELINE_ID = "option2_storyboard_v1"
ORIGINAL_SOURCE_CREDIT = "Original factory editorial graphic"
ALLOWED_MODES = {
    "LEAD", "ENTITY", "FACT", "STAT", "TIMELINE", "COMPARE",
    "PROCESS", "RANKING", "SCORECARD", "TACTICAL", "LOCATION", "QUOTE",
}

BG_TOP = (247, 244, 236)
BG_BOTTOM = (231, 238, 235)
INK = (17, 32, 34)
MUTED = (77, 97, 98)
ACCENT = (15, 104, 99)
ACCENT_2 = (226, 111, 57)
PANEL = (255, 252, 246, 238)
PANEL_LINE = (204, 214, 210)

_NUMBER_RE = re.compile(
    r"(?<!\w)(?:[$€£₹]\s*)?\d{1,3}(?:[,.]\d{3})*(?:\.\d+)?\s*"
    r"(?:%|million|billion|thousand|m|bn|k|runs?|goals?|matches?|years?|"
    r"days?|months?|points?|wins?|losses?|minutes?)?",
    re.IGNORECASE,
)
_YEAR_RE = re.compile(r"(?<!\d)(?:19\d{2}|20\d{2}|21\d{2})(?!\d)")
_SCORE_RE = re.compile(r"(?<!\d)(\d{1,3})\s*[-–:]\s*(\d{1,3})(?!\d)")
_QUOTE_RE = re.compile(r"[\"“”']([^\"“”']{8,180})[\"“”']")


def _safe_font(path: str | None, size: int):
    candidates = [
        path or "",
        os.path.join(os.path.dirname(__file__), "NotoSansDevanagari-Bold.ttf"),
        os.path.join(os.path.dirname(__file__), "NotoSansTelugu-Bold.ttf"),
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
        "/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf",
        r"C:\Windows\Fonts\segoeuib.ttf",
        r"C:\Windows\Fonts\arialbd.ttf",
    ]
    for candidate in candidates:
        try:
            if candidate and os.path.isfile(candidate):
                return ImageFont.truetype(candidate, int(size))
        except Exception:
            pass
    return ImageFont.load_default()


def _clean(value: Any) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def _sentences(text: str) -> list[str]:
    cleaned = _clean(text)
    if not cleaned:
        return []
    return [part.strip() for part in re.split(r"(?<=[.!?])\s+", cleaned) if part.strip()]


def _short(text: str, limit: int = 96) -> str:
    text = _clean(text)
    if len(text) <= limit:
        return text
    clipped = text[:limit + 1].rsplit(" ", 1)[0].strip()
    return (clipped or text[:limit]).rstrip(".,;:") + "…"


def _metrics(text: str) -> list[str]:
    found = []
    for match in _NUMBER_RE.finditer(str(text or "")):
        value = _clean(match.group(0))
        if value and value not in found:
            found.append(value)
    return found[:4]


def _years(text: str) -> list[str]:
    found = []
    for year in _YEAR_RE.findall(str(text or "")):
        if year not in found:
            found.append(year)
    return found[:5]


def _score(text: str) -> str:
    match = _SCORE_RE.search(str(text or ""))
    return f"{match.group(1)} – {match.group(2)}" if match else ""


def _quote(text: str) -> str:
    match = _QUOTE_RE.search(str(text or ""))
    return _short(match.group(1), 150) if match else ""


def _wrap(draw: ImageDraw.ImageDraw, text: str, font, max_width: int) -> list[str]:
    words = _clean(text).split()
    if not words:
        return []
    lines: list[str] = []
    current = ""
    for word in words:
        candidate = f"{current} {word}".strip()
        try:
            width = draw.textbbox((0, 0), candidate, font=font)[2]
        except Exception:
            width = len(candidate) * max(8, getattr(font, "size", 16))
        if current and width > max_width:
            lines.append(current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(current)
    return lines


def _draw_wrapped(draw, xy, text, font, fill, max_width, line_gap=10, max_lines=None):
    lines = _wrap(draw, text, font, max_width)
    if max_lines and len(lines) > max_lines:
        lines = lines[:max_lines]
        lines[-1] = _short(lines[-1], max(16, len(lines[-1])))
    x, y = xy
    line_height = int(getattr(font, "size", 30) * 1.12)
    for line in lines:
        draw.text((x, y), line, font=font, fill=fill)
        y += line_height + line_gap
    return y


def _canvas(font_path: str | None, kicker: str, mode: str):
    width, height = 1080, 1920
    image = Image.new("RGBA", (width, height), BG_TOP + (255,))
    draw = ImageDraw.Draw(image)
    for y in range(height):
        ratio = y / max(1, height - 1)
        color = tuple(int(BG_TOP[i] * (1 - ratio) + BG_BOTTOM[i] * ratio) for i in range(3)) + (255,)
        draw.line((0, y, width, y), fill=color)

    # restrained deterministic texture; the visual language stays original.
    for idx in range(18):
        x = 40 + ((idx * 193) % 980)
        y = 160 + ((idx * 317) % 1500)
        radius = 8 + (idx % 4) * 5
        draw.ellipse((x - radius, y - radius, x + radius, y + radius), fill=(255, 255, 255, 38))

    draw.rounded_rectangle(
        (58, 58, 1022, 1862), radius=42,
        fill=(255, 255, 255, 85), outline=PANEL_LINE + (170,), width=2,
    )
    draw.text((90, 96), _short(kicker.upper(), 42), font=_safe_font(font_path, 28), fill=ACCENT)
    pill_font = _safe_font(font_path, 22)
    mode_text = mode.replace("_", " ")
    box = draw.textbbox((0, 0), mode_text, font=pill_font)
    pill_w = box[2] - box[0] + 42
    draw.rounded_rectangle(
        (1022 - pill_w - 38, 88, 1022 - 38, 144),
        radius=28, fill=ACCENT + (24,), outline=ACCENT + (80,), width=2,
    )
    draw.text((1022 - pill_w - 17, 102), mode_text, font=pill_font, fill=ACCENT)
    return image, draw


def _panel(draw, box, radius=30):
    draw.rounded_rectangle(box, radius=radius, fill=PANEL, outline=PANEL_LINE, width=2)


def _accent_bar(draw, x, y, width, height=12):
    draw.rounded_rectangle((x, y, x + width, y + height), radius=height // 2, fill=ACCENT)


def _deterministic_mode(scene: dict[str, Any], index: int) -> str:
    text = _clean(scene.get("voiceover"))
    intent = _clean(scene.get("visual_intent"))
    category = _clean(scene.get("sport_or_topic_category")).lower()
    lower = f"{text} {intent}".lower()
    if index == 0:
        return "LEAD"
    if _quote(text):
        return "QUOTE"
    if _score(text) and any(token in lower for token in ("score", "won", "beat", "defeat", "match", "final")):
        return "SCORECARD"
    if any(token in lower for token in (
        "timeline", "since", "before", "after", "in 2019", "in 2020",
        "in 2021", "in 2022", "in 2023", "in 2024", "in 2025", "in 2026",
    )) and len(_years(text)) >= 2:
        return "TIMELINE"
    if any(token in lower for token in ("compared", "versus", " vs ", "against", "more than", "less than")):
        return "COMPARE"
    if any(token in lower for token in ("step", "how it works", "process", "works like", "first", "then", "finally")):
        return "PROCESS"
    if any(token in lower for token in ("top ", "ranked", "ranking", "number one", "second", "third", "most", "least")):
        return "RANKING"
    if any(token in lower for token in (
        "formation", "press", "pressing", "batting", "bowling", "tactic",
        "tactical", "lineup", "line-up", "xi", "shape",
    )) and any(token in category for token in ("sport", "cricket", "football", "soccer")):
        return "TACTICAL"
    if _metrics(text):
        return "STAT"
    if any(token in lower for token in ("city", "country", "state", "located", "based in", "from ")):
        return "LOCATION"
    if scene.get("primary_entity"):
        return "ENTITY"
    return "FACT"


def _planner_prompt(script_data: dict[str, Any], scenes: list[dict[str, Any]]) -> str:
    scene_lines = []
    for index, scene in enumerate(scenes, 1):
        scene_lines.append(
            f"SCENE {index}\n"
            f"VOICEOVER: {_clean(scene.get('voiceover'))}\n"
            f"ENTITY: {_clean(scene.get('primary_entity'))}\n"
            f"VISUAL INTENT: {_clean(scene.get('visual_intent'))}\n"
            f"CATEGORY: {_clean(scene.get('sport_or_topic_category'))}\n"
        )
    evidence = _clean(script_data.get("research_evidence_text"))[:9000]
    return (
        "You are an editorial motion-graphics director. Choose only the best visual form for each scene. "
        "Do NOT invent facts, people, numbers, quotes, dates, locations or logos. The render engine will only "
        "display information already present in the supplied scene voiceover/evidence. Return JSON only.\n\n"
        "ALLOWED MODES: LEAD, ENTITY, FACT, STAT, TIMELINE, COMPARE, PROCESS, RANKING, SCORECARD, TACTICAL, LOCATION, QUOTE.\n"
        "Rules: scene 1 should normally be LEAD; use SCORECARD only when an explicit score exists; use QUOTE only when quoted text exists; "
        "use TIMELINE only when at least two dates/years appear; use TACTICAL only when the scene is genuinely sports tactical; "
        "otherwise prefer FACT, ENTITY or STAT. Keep the plan minimal and varied.\n\n"
        f"TITLE: {_clean(script_data.get('title') or (script_data.get('titles') or [''])[0])}\n"
        f"EVIDENCE: {evidence}\n\n" +
        "\n".join(scene_lines) +
        "\n\nOUTPUT: {\"scenes\":[{\"mode\":\"LEAD|ENTITY|FACT|STAT|TIMELINE|COMPARE|PROCESS|RANKING|SCORECARD|TACTICAL|LOCATION|QUOTE\"}]}"
    )


def _post_json(url: str, headers: dict[str, str], payload: dict[str, Any], timeout: int = 30):
    try:
        response = requests.post(url, headers=headers, json=payload, timeout=timeout)
        if response.status_code != 200:
            return None
        data = response.json()
        return data if isinstance(data, dict) else None
    except Exception:
        return None


def _llm_plan(script_data: dict[str, Any], scenes: list[dict[str, Any]]) -> tuple[list[str], str]:
    prompt = _planner_prompt(script_data, scenes)
    groq_key = os.getenv("GROQ_API_KEY", "").strip()
    if groq_key:
        result = _post_json(
            "https://api.groq.com/openai/v1/chat/completions",
            {"Authorization": f"Bearer {groq_key}", "Content-Type": "application/json"},
            {
                "model": "openai/gpt-oss-120b",
                "messages": [
                    {"role": "system", "content": "Return only valid JSON matching the requested schema."},
                    {"role": "user", "content": prompt},
                ],
                "response_format": {"type": "json_object"},
                "temperature": 0.15,
            },
        )
        try:
            raw = result["choices"][0]["message"]["content"] if result else ""
            parsed = json.loads(raw)
            modes = [
                str(item.get("mode") or "").upper()
                for item in parsed.get("scenes", [])
                if isinstance(item, dict)
            ]
            if modes:
                return modes, "groq"
        except Exception:
            pass

    gemini_key = os.getenv("GEMINI_API_KEY", "").strip()
    if gemini_key:
        result = _post_json(
            "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.6-flash:generateContent?key="
            + gemini_key,
            {"Content-Type": "application/json"},
            {
                "contents": [{"role": "user", "parts": [{"text": prompt}]}],
                "generationConfig": {"temperature": 0.15, "responseMimeType": "application/json"},
            },
        )
        try:
            raw = result["candidates"][0]["content"]["parts"][0]["text"] if result else ""
            parsed = json.loads(raw)
            modes = [
                str(item.get("mode") or "").upper()
                for item in parsed.get("scenes", [])
                if isinstance(item, dict)
            ]
            if modes:
                return modes, "gemini"
        except Exception:
            pass

    return [], "deterministic"


def _normalise_modes(llm_modes: list[str], scenes: list[dict[str, Any]]) -> list[str]:
    fallback = [_deterministic_mode(scene, index) for index, scene in enumerate(scenes)]
    result: list[str] = []
    for index, scene in enumerate(scenes):
        candidate = str(llm_modes[index] if index < len(llm_modes) else "").upper().strip()
        if candidate not in ALLOWED_MODES:
            candidate = fallback[index]
        if candidate == "SCORECARD" and not _score(scene.get("voiceover", "")):
            candidate = fallback[index]
        if candidate == "QUOTE" and not _quote(scene.get("voiceover", "")):
            candidate = fallback[index]
        if candidate == "TIMELINE" and len(_years(scene.get("voiceover", ""))) < 2:
            candidate = fallback[index]
        result.append(candidate)
    if result:
        result[0] = "LEAD"
    return result


